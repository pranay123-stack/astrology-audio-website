/**
 * Creates .env.local for local mode with a random session secret and an admin
 * login. The generated password is printed once; only its scrypt hash is stored.
 *
 *   npm run setup:local -- --email you@example.com [--password '...'] [--force]
 */
import { randomBytes } from "node:crypto";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { hashPassword } from "../src/lib/auth/tokens";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function main() {
  const file = ".env.local";
  if (existsSync(file) && !process.argv.includes("--force")) {
    console.error(`${file} already exists. Re-run with --force to replace it.`);
    process.exit(1);
  }
  const email = (arg("email") ?? "admin@example.com").toLowerCase();
  const password = arg("password") ?? randomBytes(12).toString("base64url");
  if (password.length < 10) {
    console.error("Use a password of at least 10 characters.");
    process.exit(1);
  }
  const env = [
    "# Generated by `npm run setup:local`. Local mode: data in .data/, no Supabase.",
    "NEXT_PUBLIC_DATA_BACKEND=local",
    "NEXT_PUBLIC_SITE_URL=http://localhost:3460",
    "# Lets `npm run build && npm start` run in local mode on this computer. Never set this on a real host.",
    "ALLOW_LOCAL_BACKEND_IN_PRODUCTION=true",
    `SESSION_SECRET=${randomBytes(32).toString("base64url")}`,
    `ADMIN_EMAIL=${email}`,
    `ADMIN_PASSWORD_HASH=${await hashPassword(password)}`,
    "",
  ].join("\n");
  await writeFile(file, env, { mode: 0o600 });
  console.log(`Wrote ${file}.`);
  console.log(`Admin login: ${email}`);
  console.log(`Password:    ${password}`);
  console.log("Store this password now; it is not saved anywhere in plain text.");
}

main();
